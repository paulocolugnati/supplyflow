def translate(key, lang):
    """EN: Return the text for key in lang, falling back to Portuguese, then to the key.
    PT: Devolve o texto da chave no idioma, caindo para o português e depois para a chave.
    """
    return TRANSLATIONS.get(lang, {}).get(key) or TRANSLATIONS[DEFAULT_LANGUAGE].get(key) or key


def customer_text(key):
    """EN: Text of a message that goes to a customer on WhatsApp. Always Portuguese: the
        customer is a Brazilian business, whatever language the seller uses on screen.
    PT: Texto de uma mensagem que vai para um cliente no WhatsApp. Sempre em português: o
        cliente é uma empresa brasileira, seja qual for o idioma que o vendedor usa na tela.
    """
    return translate(key, DEFAULT_LANGUAGE)


def current_lang():
    """EN: Language chosen in the session, or the default.
    PT: Idioma escolhido na sessão, ou o padrão.
    """
    lang = session.get("lang", DEFAULT_LANGUAGE)
    return lang if lang in LANGUAGES else DEFAULT_LANGUAGE


def _(key):
    """EN: Shortcut to translate a text in Python code (flash messages, errors).
    PT: Atalho para traduzir um texto no código Python (mensagens, erros).
    """
    return translate(key, current_lang())
